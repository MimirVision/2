export const STRINGS: Record<Language, Record<StringKey, string>> = { en, nb };

export function translate(lang: Language, key: StringKey, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Norwegian (bokmål/nynorsk) speakers get Norwegian, everyone else English. */
export function languageFor(code: string | null | undefined): Language {
  return code === 'nb' || code === 'nn' || code === 'no' ? 'nb' : 'en';
}

